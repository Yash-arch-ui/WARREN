//! `warren serve` — a loopback HTTP surface over the existing client core.
//!
//! This module owns **no protocol logic**. Every cryptographic and routing
//! step is delegated to the already-tested modules:
//!
//! - message bodies: [`crate::ratchet::RatchetClient::encrypt`] / `decrypt`
//! - admission proofs: [`crate::credential::ClientTokenWallet::spend_token`]
//! - path verification + transmit: [`crate::client::send_packet`]
//! - directory trust: [`crate::directory::SignedRelayList`] via `send_packet`
//! - delivery frames: [`crate::net::recv_frame`]
//!
//! What it *does* add is the two things a mixnet does not carry natively and
//! a message-bus consumer needs:
//!
//! 1. **A message id and a room label on the wire.** A caller that sends a
//!    message expects the receiver to report the *same* id, and to know which
//!    logical room it belonged to. Both ride inside the ratchet-encrypted
//!    body, so relays never see them.
//! 2. **Chunking.** A Sphinx payload holds [`crate::client::MAX_MSG_LEN`]
//!    (~705 B) of plaintext; bus payloads are routinely larger. Messages are
//!    split across packets and reassembled here. Each chunk is a separate
//!    packet and therefore **spends one admission token**.
//!
//! Ordering is best-effort by construction: Poisson per-hop mix delays
//! reorder packets on purpose, so a monotonic per-sender counter plus a short
//! reorder window ([`REORDER_WINDOW`]) restores FIFO when it can and releases
//! out of order rather than stalling when it cannot.
//!
//! The server binds loopback only — see [`serve`].

